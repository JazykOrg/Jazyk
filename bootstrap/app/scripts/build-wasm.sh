#!/bin/sh
# Build the browser backend: the wasm library, its bindings, and a stable re-export
# for the model bridge. The demo fixtures are packed separately by pack-demos.sh.
# See docs/frontends/wasm.md#building.
set -e
cd "$(dirname "$0")/../.."   # bootstrap/

OUT=app/src/wasm-backend
PROFILE=${JAZYK_WASM_PROFILE:-release}

# The wasm target lives in the rustup toolchain, and PATH may lead to another
# installation (a Homebrew rustc has no wasm std). cargo finds rustc through PATH,
# so the toolchain's own bin goes first and the pair stays matched.
CARGO=${CARGO:-$(rustup which cargo 2>/dev/null || command -v cargo)}
case "$CARGO" in
  */toolchains/*) PATH="$(dirname "$CARGO"):$PATH"; export PATH ;;
esac

echo "==> cargo build --target wasm32-unknown-unknown --lib ($PROFILE)"
if [ "$PROFILE" = "release" ]; then
  "$CARGO" build --target wasm32-unknown-unknown --lib --release
  WASM=target/wasm32-unknown-unknown/release/jazyk.wasm
else
  "$CARGO" build --target wasm32-unknown-unknown --lib
  WASM=target/wasm32-unknown-unknown/debug/jazyk.wasm
fi

echo "==> wasm-bindgen"
rm -rf "$OUT/snippets"
wasm-bindgen --target web --out-dir "$OUT" --no-typescript "$WASM"

# wasm-bindgen names the snippet directory after a content hash, so the worker
# imports this file instead and the hash stays out of the source.
SNIPPET=$(cd "$OUT" && find snippets -name bridge.js | head -1)
if [ -z "$SNIPPET" ]; then
  echo "no bridge.js snippet emitted" >&2
  exit 1
fi
cat > "$OUT/bridge.js" <<EOF
// Generated by scripts/build-wasm.sh. wasm-bindgen names the snippet directory
// after a content hash; the worker imports this stable path instead.
export { installBridge, bridgeReady } from './$SNIPPET'
EOF

ls -la "$OUT"/jazyk_bg.wasm
